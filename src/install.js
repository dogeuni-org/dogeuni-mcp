import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_EXTENSION_ID, HOST_NAME, defaultHostsDir, ensureHomeDir, launcherPath } from './paths.js';

const EXTENSION_ID_RE = /^[a-p]{32}$/;

export const manifestFileName = `${HOST_NAME}.json`;

/** Absolute path of the host entry point that the launcher execs. */
export const hostEntryPath = () => fs.realpathSync(fileURLToPath(new URL('../bin/host.js', import.meta.url)));

/** Double-quote a string for sh, escaping the characters that stay special inside "". */
const shQuote = (s) => `"${s.replace(/[\\"$`]/g, (c) => `\\${c}`)}"`;

export function launcherScript(nodePath, hostEntry) {
  return `#!/bin/sh\n# Generated by dogeuni-mcp install. Chrome does not pass the shell PATH, so paths are absolute.\nexec ${shQuote(nodePath)} ${shQuote(hostEntry)}\n`;
}

export function hostManifest(launcher, extensionId) {
  return {
    name: HOST_NAME,
    description: 'DogeUni wallet agent bridge (dogeuni-mcp)',
    path: launcher,
    type: 'stdio',
    allowed_origins: [`chrome-extension://${extensionId}/`],
  };
}

function resolveHostsDir(hostsDir, platform) {
  if (hostsDir) return path.resolve(hostsDir);
  const d = defaultHostsDir(platform);
  if (!d) throw new Error(`Unsupported platform "${platform}": dogeuni-mcp supports macOS and Linux only.`);
  return d;
}

/**
 * @param {{ home: string, extensionId?: string, hostsDir?: string, platform?: NodeJS.Platform, nodePath?: string, hostEntry?: string }} opts
 */
export function install({ home, extensionId = DEFAULT_EXTENSION_ID, hostsDir, platform = process.platform, nodePath = process.execPath, hostEntry = hostEntryPath() }) {
  if (platform !== 'darwin' && platform !== 'linux') {
    throw new Error(`Unsupported platform "${platform}": dogeuni-mcp supports macOS and Linux only.`);
  }
  if (!EXTENSION_ID_RE.test(extensionId)) throw new Error(`Invalid extension id "${extensionId}" (expected 32 letters a–p).`);
  if (!path.isAbsolute(nodePath) || !path.isAbsolute(hostEntry)) throw new Error('node and host paths must be absolute');
  const dir = resolveHostsDir(hostsDir, platform);

  ensureHomeDir(home);
  const launcher = launcherPath(home);
  fs.writeFileSync(launcher, launcherScript(nodePath, hostEntry), { mode: 0o755 });
  fs.chmodSync(launcher, 0o755);

  fs.mkdirSync(dir, { recursive: true });
  const manifest = path.join(dir, manifestFileName);
  fs.writeFileSync(manifest, JSON.stringify(hostManifest(launcher, extensionId), null, 2) + '\n', { mode: 0o644 });
  return { manifest, launcher };
}

/**
 * Removes the manifest and the launcher. Leaves credentials.json alone.
 * @param {{ home: string, hostsDir?: string, platform?: NodeJS.Platform }} opts
 * @returns {string[]} removed paths
 */
export function uninstall({ home, hostsDir, platform = process.platform }) {
  const dir = resolveHostsDir(hostsDir, platform);
  const removed = [];
  for (const p of [path.join(dir, manifestFileName), launcherPath(home)]) {
    try {
      fs.unlinkSync(p);
      removed.push(p);
    } catch (err) {
      if (err.code !== 'ENOENT') throw err;
    }
  }
  return removed;
}
